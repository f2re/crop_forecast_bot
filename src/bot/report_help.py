def format_risk_help() -> str:
    return (
        "⚠️ <b>Как читать варианты прогноза</b>\n\n"
        "Бот получает несколько расчётов одной модели с немного различающимися "
        "начальными условиями. Если условие показывают 25 из 31 вариантов, это "
        "означает высокую согласованность текущего запуска.\n\n"
        "Это число не является автоматически вероятностью повреждения растений. "
        "Порог относится к погоде — температуре, осадкам, ветру или запасу "
        "энергии для конвекции. Реакция культуры зависит от сорта, стадии, почвы "
        "и агротехники.\n\n"
        "Ближайшие 3–5 суток полезнее для действий. Дальний срок следует считать "
        "предварительным и проверять после следующих обновлений."
    )


def format_report_help(
    topic: ReportHelpTopic,
    *,
    crop_key: str,
    season_start_date: date | None,
    current_phase: str | None,
    today: date,
) -> str:
    if topic == "heat":
        return format_heat_help(crop_key)
    if topic == "water":
        return format_water_help()
    if topic == "htc":
        return format_htc_help()
    if topic == "phase":
        return format_phase_help(
            crop_key,
            season_start_date=season_start_date,
            current_phase=current_phase,
            today=today,
        )
    if topic == "sources":
        return format_sources_help()
    if topic == "risk":
        return format_risk_help()
    raise ValueError("Неизвестный раздел справки.")
