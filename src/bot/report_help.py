from __future__ import annotations

import html
from datetime import date
from typing import Literal

from src.agro.crop_catalog import get_crop, get_crop_name

ReportHelpTopic = Literal["heat", "water", "htc", "phase", "sources", "risk"]


def _heat_example(crop_key: str) -> tuple[float, float, float, float]:
    crop = get_crop(crop_key)
    t_base = float(crop["t_base"])
    t_max = 28.0
    t_min = 16.0
    mean = (t_max + t_min) / 2.0
    daily = max(0.0, mean - t_base)
    return t_max, t_min, mean, daily


def format_heat_help(crop_key: str) -> str:
    crop = get_crop(crop_key)
    crop_name = html.escape(get_crop_name(crop_key))
    t_base = float(crop["t_base"])
    t_upper = crop["t_upper"]
    t_max, t_min, mean, daily = _heat_example(crop_key)
    upper_note = (
        f" Для этой культуры средняя температура дополнительно ограничивается "
        f"сверху значением {float(t_upper):.1f} °C."
        if t_upper is not None
        else " Верхний температурный предел для этой культуры пока не задан."
    )
    return (
        "🌡 <b>Как считается накопленное тепло</b>\n\n"
        f"Для культуры «{crop_name}» используется базовая температура "
        f"<b>{t_base:.1f} °C</b>. За каждые завершённые местные сутки бот:\n"
        "1. берёт максимальную и минимальную температуру воздуха на высоте 2 м;\n"
        "2. находит их среднее;\n"
        "3. вычитает базовую температуру;\n"
        "4. отрицательный результат заменяет нулём;\n"
        "5. складывает суточные значения от указанной даты.\n\n"
        "<code>тепло за сутки = max(0, (Tмакс + Tмин) / 2 − Tбаза)</code>\n\n"
        f"<b>Пример:</b> Tмакс={t_max:.0f} °C, Tмин={t_min:.0f} °C, "
        f"средняя={mean:.0f} °C. За сутки добавится "
        f"<b>{daily:.1f} °C·сут</b>.{upper_note}\n\n"
        "Это показатель температурного накопления, а не измерение роста растения. "
        "Базовая температура зависит от культуры, сорта и принятого метода. "
        "Поэтому одно число нельзя без отдельной проверки превращать в точную "
        "стадию развития.\n\n"
        "Источник метода: McMaster и Wilhelm, 1997."
    )


def format_water_help() -> str:
    return (
        "💧 <b>Как считаются осадки и испарение</b>\n\n"
        "<b>Осадки</b> — суточная сумма дождя и водного эквивалента снега из "
        "Open-Meteo. Это расчёт модели или восстановленный ряд прошлой погоды, "
        "а не показание дождемера на поле.\n\n"
        "Бот складывает только завершённые местные сутки. Текущий день и прогноз "
        "не входят в накопленную сумму. Отрицательные и отсутствующие значения "
        "не заменяются нулём.\n\n"
        "<b>Эталонное испарение</b> — расчёт для хорошо увлажнённой травяной "
        "поверхности по методу ФАО-56. Оно показывает испаряющую способность "
        "погоды, но не фактический расход воды томатом, картофелем или другой "
        "культурой.\n\n"
        "<b>Пример:</b> за сутки выпало 3 мм, эталонное испарение составило "
        "6 мм. Разность равна −3 мм. Это не означает, что нужно полить ровно "
        "3 мм: не учтены почва, корни, сток, полив и состояние растений.\n\n"
        "Сухими считаются сутки с осадками менее 1 мм. Длина сухой серии "
        "показывается только при непрерывном ряде без пропущенных дат."
    )


def format_htc_help() -> str:
    return (
        "🌦 <b>Что означает показатель увлажнения</b>\n\n"
        "ГТК Селянинова сопоставляет осадки и накопленное тепло тёплого периода:\n\n"
        "<code>ГТК = 10 × сумма осадков / сумма средних температур</code>\n\n"
        "В расчёт входят только завершённые сутки со средней температурой выше "
        "10 °C. Бот требует заданную дату начала сезона, непрерывный ряд и не "
        "менее 20 тёплых суток.\n\n"
        "<b>Пример:</b> сумма осадков 80 мм, сумма средних температур тёплых "
        "суток 1000 °C. ГТК = 10 × 80 / 1000 = 0,80.\n\n"
        "Одинаковое значение может иметь разный смысл для разных культур, почв "
        "и районов. Поэтому бот показывает число и качество ряда, но не выдаёт "
        "универсальный диагноз засухи или норму полива."
    )


def format_phase_help(
    crop_key: str,
    *,
    season_start_date: date | None,
    current_phase: str | None,
    today: date,
) -> str:
    crop_name = html.escape(get_crop_name(crop_key))
    phase = html.escape(current_phase) if current_phase else "не указана"
    if season_start_date is None:
        age_line = "Дата посева или начала сезона не задана."
    elif today < season_start_date:
        age_line = "Указанная дата находится в будущем и должна быть исправлена."
    else:
        age_line = (
            f"С указанной даты прошло <b>{(today - season_start_date).days} сут.</b>"
        )
    return (
        "🌿 <b>Почему бот сам не меняет стадию</b>\n\n"
        f"Культура: <b>{crop_name}</b>. Текущая стадия: <b>{phase}</b>. "
        f"{age_line}\n\n"
        "Календарный возраст и накопленное тепло помогают оценить срок, но не "
        "доказывают фактическую стадию. Для томата особенно важны:\n"
        "• какая дата введена — посев, всходы или высадка рассады;\n"
        "• открытый грунт или теплица;\n"
        "• детерминантный или индетерминантный сорт;\n"
        "• жара, освещение, питание, полив и состояние растений.\n\n"
        "Сейчас бот хранит наблюдение пользователя как источник истины и не "
        "подменяет его догадкой. Следующий этап — напоминание: «стадия давно не "
        "подтверждалась; возможно, пора выбрать следующую». Предложение будет "
        "показываться отдельно и никогда не заменит наблюдение без подтверждения."
    )


