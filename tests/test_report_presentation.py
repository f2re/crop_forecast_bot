def test_compact_report_keeps_actions_and_removes_internal_terms() -> None:
    text = compact_agro_report(
        FULL_REPORT,
        season_start_date=date(2026, 4, 15),
        today=date(2026, 8, 3),
        source="Open-Meteo",
    )

    assert "Отчёт по полю" in text
    assert "С указанной даты прошло <b>110 сут.</b>" in text
    assert "978.9 °C·сут" in text
    assert "базовая температура — 10.0 °C" in text
    assert "125.5 °C·сут" in text
    assert "155.2 мм" in text
    assert "осадков было на <b>40.0 мм меньше</b>" in text
    assert "Без заметных осадков: <b>5 сут.</b>" in text
    assert "Показатель увлажнения (ГТК): <b>0.75</b>" in text
    assert "Основные показатели выше рассчитаны без этого блока" in text

    for internal_term in (
        "operational_past",
        "reanalysis",
        "best_match",
        "endpoint",
        "Tbase",
        "P−ET₀",
        "ET₀",
        "провайдера",
        "валидным",
    ):
        assert internal_term not in text

    assert len(text) < len(FULL_REPORT)
    assert len(text) <= 4096


def test_recent_date_does_not_create_premature_stage_reminder() -> None:
    text = compact_agro_report(
        FULL_REPORT,
        season_start_date=date(2026, 7, 25),
        today=date(2026, 8, 3),
        source="Open-Meteo",
    )

    assert "Бот не меняет стадию" not in text
